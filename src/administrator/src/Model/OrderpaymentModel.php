	 *
	 * @since   1.6
	 */
	protected function loadFormData()
	{
		// Check the session for previously entered form data.
		$app  = Factory::getApplication();
		$data = $app->getUserState('com_mymuse.edit.orderpayment.data', array());

		if (empty($data))
		{
			$data = $this->getpayment();

			// Prime some default values.
			if ($this->getState('orderpayment.id') == 0)
			{
				$filters     = (array) $app->getUserState('com_mymuse.orderpayment.filter');
			}
		}

		$this->preprocessData('com_mymuse.orderpayment', $data);

		return $data;
	}


